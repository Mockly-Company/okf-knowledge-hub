import type { Meta, StoryObj } from "@storybook/react-vite";
import { expect, screen, waitFor, within } from "storybook/test";
import { DocumentsPage } from "./DocumentsPage";
import { withAppProviders } from "@/stories/decorators/AppProviders";
import { PageStoryFrame } from "@/stories/decorators/PageStoryFrame";

const meta = { title: "Pages/NewDocument", component: DocumentsPage, parameters: { layout: "fullscreen" }, decorators: [withAppProviders({ router: { initialEntries: ["/documents"] } })], render: () => <PageStoryFrame><DocumentsPage /></PageStoryFrame> } satisfies Meta<typeof DocumentsPage>;
export default meta;
export const Default: StoryObj<typeof meta> = { play: async ({ canvas, userEvent }) => {
  const buttons = await canvas.findAllByRole("button", { name: "새 문서" });
  await userEvent.click(buttons[buttons.length - 1]);
  await waitFor(() => expect(screen.getByRole("dialog")).toBeVisible());
  const dialog = within(screen.getByRole("dialog"));
  const title = dialog.getByLabelText("제목");
  const folder = dialog.getByRole("button", { name: "저장 폴더 선택" });
  const folderLabel = dialog.getByText("저장 폴더", {exact: true});
  const templateLabel = dialog.getByText("템플릿", {exact: true});
  const titleToFolder = folderLabel.getBoundingClientRect().top - title.getBoundingClientRect().bottom;
  const folderToTemplate = templateLabel.getBoundingClientRect().top - folder.getBoundingClientRect().bottom;
  await expect(Math.abs(titleToFolder - folderToTemplate)).toBeLessThanOrEqual(1);
  await expect(dialog.queryByRole("textbox", {name: "파일명"})).not.toBeInTheDocument();
  await expect(title.getBoundingClientRect().top).toBeLessThan(folder.getBoundingClientRect().top);
  await userEvent.type(title, "지도 API");
  await userEvent.click(dialog.getByRole("combobox", { name: "템플릿" }));
  await userEvent.click(await screen.findByRole("option", { name: /API 계약/ }));
  const preview = dialog.getByRole("region", { name: "템플릿 미리보기" });
  await expect(within(preview).getByRole("heading", { name: "지도 검색 API 계약" })).toBeVisible();
  await expect(within(preview).getByRole("heading", { name: "공통 계약" })).toBeVisible();
  const frame = dialog.getByRole("group", { name: "템플릿 본문 미리보기" });
  await expect(getComputedStyle(frame).overflowY).toBe("auto");
  await expect(parseFloat(getComputedStyle(frame).borderTopWidth)).toBe(1);
  await expect(frame).toHaveAttribute("tabindex", "0");
  await expect(parseFloat(getComputedStyle(within(preview).getByRole("heading", { name: "지도 검색 API 계약" })).fontSize)).toBeLessThan(28);
  const left = title.getBoundingClientRect();
  const right = preview.getBoundingClientRect();
  if (window.innerWidth > 800) {
    await expect(right.left).toBeGreaterThan(left.right);
  } else {
    await expect(right.top).toBeGreaterThan(folder.getBoundingClientRect().bottom);
  }
  await userEvent.click(dialog.getByRole("combobox", { name: "템플릿" }));
  await userEvent.click(await screen.findByRole("option", { name: /빈 문서/ }));
  await userEvent.clear(title);
  await userEvent.click(folder);
  await userEvent.click(await screen.findByRole("menuitemradio", {name: "api"}));
  await userEvent.click(await dialog.findByRole("button", {name: "새 폴더 만들기"}));
  const folderName = dialog.getByRole("textbox", {name: "새 폴더 이름"});
  await expect(dialog.getByRole("button", {name: "추가"})).toBeDisabled();
  await userEvent.type(folderName, "v2/contracts/");
  await expect(folderName).toHaveValue("");
  await expect(folderName).toHaveAttribute("placeholder", "");
  await expect(dialog.getByText("v2")).toHaveAttribute("data-folder-state", "new");
  await userEvent.type(folderName, "yeah");
  await expect(folderName.getBoundingClientRect().width).toBeLessThan(100);
  await userEvent.clear(folderName);
  await userEvent.click(dialog.getByRole("button", {name: "추가"}));
  await expect(folder).toHaveTextContent("docs / api / v2 / contracts");
  await userEvent.click(dialog.getByRole("button", {name: "생성 예정 폴더 추가 취소"}));
  await expect(folder).toHaveTextContent("docs / api");
  await userEvent.click(folder);
  await userEvent.keyboard("{Escape}");
  await waitFor(() => expect(folder).toHaveFocus());
} };
